#!/usr/bin/env node

/**
 * ALTERNATIVE: Generates PWA assets with AUTOMATIC versioning
 * Uses build timestamp so every deployment triggers service worker update
 *
 * To use this instead of the manual version:
 * 1. Rename this file to generate-pwa-assets.js (backup the original)
 * 2. OR update package.json scripts to use this file instead
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// AUTOMATIC VERSION GENERATION
// Choose one strategy:

// Strategy 1: Use build timestamp (changes every build)
const APP_VERSION = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
// Example: 2024-03-02T15-30-45

// Strategy 2: Use git commit hash (changes per commit)
// Uncomment to use:
// const APP_VERSION = execSync('git rev-parse --short HEAD').toString().trim();
// Example: abc1234

// Strategy 3: Use package.json version + timestamp
// Uncomment to use:
// const packageJson = require('../package.json');
// const APP_VERSION = `${packageJson.version}-${Date.now()}`;
// Example: 1.0.0-1234567890

console.log(`📦 Generating PWA assets with AUTO version ${APP_VERSION}...`);

// ============================================================================
// Generate manifest.json
// ============================================================================
const manifest = {
  name: "Metric Gym Manager",
  short_name: "Metric Gym",
  start_url: "/members",
  display: "standalone",
  background_color: "#ffffff",
  theme_color: "#000000",
  icons: [
    {
      src: `/icon-192.png?v=${APP_VERSION}`,
      sizes: "192x192",
      type: "image/png"
    },
    {
      src: `/icon-512.png?v=${APP_VERSION}`,
      sizes: "512x512",
      type: "image/png"
    }
  ]
};

const manifestPath = path.join(__dirname, '../public/manifest.json');
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
console.log('✅ Generated manifest.json');

// ============================================================================
// Generate service-worker.js
// ============================================================================
const serviceWorker = `// service-worker.js
// Auto-generated by scripts/generate-pwa-assets.js - DO NOT EDIT MANUALLY
const CACHE_NAME = 'saas-app-v${APP_VERSION}';
const STATIC_ASSETS = [
  '/icon-192.png?v=${APP_VERSION}',
  '/icon-512.png?v=${APP_VERSION}',
  '/logo.svg',
];

// Install event: Cache static assets but DON'T auto-activate
// We wait for user confirmation via SKIP_WAITING message
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS);
    })
  );
  // Don't call skipWaiting() here anymore - wait for user action
});

// Message event: Handle commands from the client
self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') {
    // User clicked "Refresh Now" - activate immediately
    self.skipWaiting();
  }
});

// Activate event: Clean up old caches and notify clients
self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Clean up old caches
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter((name) => name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      );

      // Take control of all pages immediately
      await self.clients.claim();

      // Notify all clients to reload
      const clients = await self.clients.matchAll({ type: 'window' });
      clients.forEach((client) => {
        client.postMessage({ type: 'RELOAD_PAGE' });
      });
    })()
  );
});

// Fetch event: Network-first for navigation, cache-first for static assets
self.addEventListener('fetch', (event) => {
  const { request } = event;

  // Navigation requests (HTML pages): always go to network so middleware
  // redirects work correctly. Fall back to cache only if offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => {
        return caches.match(request);
      })
    );
    return;
  }

  // Static assets: serve from cache, fall back to network
  event.respondWith(
    caches.match(request).then((cached) => {
      return cached || fetch(request);
    })
  );
});
`;

const serviceWorkerPath = path.join(__dirname, '../public/service-worker.js');
fs.writeFileSync(serviceWorkerPath, serviceWorker);
console.log('✅ Generated service-worker.js');

// ============================================================================
// Generate version info for layout.tsx to consume
// ============================================================================
const versionInfo = `// Auto-generated by scripts/generate-pwa-assets.js - DO NOT EDIT MANUALLY
export const PWA_VERSION = '${APP_VERSION}';
`;

const versionPath = path.join(__dirname, '../src/lib/pwa-version.ts');
fs.writeFileSync(versionPath, versionInfo);
console.log('✅ Generated src/lib/pwa-version.ts');

console.log(`\n🎉 All PWA assets generated successfully with AUTO version ${APP_VERSION}!\n`);
console.log('⚠️  NOTE: This will trigger update banner on EVERY deployment.\n');
