#!/usr/bin/env node

/**
 * Generates PWA assets (manifest.json, service-worker.js) with automated versioning
 * Version is sourced from package.json to ensure consistency across all PWA files
 */

const fs = require('fs');
const path = require('path');

// Read version from package.json (single source of truth)
const packageJson = require('../package.json');
const APP_VERSION = packageJson.version;

console.log(`📦 Generating PWA assets with version ${APP_VERSION}...`);

// ============================================================================
// Generate manifest.json
// ============================================================================
const manifest = {
  name: "Metric Gym Manager",
  short_name: "Metric Gym",
  description: "Modern gym and fitness center management platform",
  start_url: "/members",
  scope: "/",
  display: "standalone",
  orientation: "portrait",
  background_color: "#ffffff",
  theme_color: "#000000",
  categories: ["business", "fitness"],
  lang: "en",
  icons: [
    {
      src: `/icon-192.png?v=${APP_VERSION}`,
      sizes: "192x192",
      type: "image/png",
      purpose: "any"
    },
    {
      src: `/icon-512.png?v=${APP_VERSION}`,
      sizes: "512x512",
      type: "image/png",
      purpose: "any"
    },
    {
      src: `/icon-maskable-192.png?v=${APP_VERSION}`,
      sizes: "192x192",
      type: "image/png",
      purpose: "maskable"
    },
    {
      src: `/icon-maskable-512.png?v=${APP_VERSION}`,
      sizes: "512x512",
      type: "image/png",
      purpose: "maskable"
    }
  ]
};

const manifestPath = path.join(__dirname, '../public/manifest.json');
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
console.log('✅ Generated manifest.json');

// ============================================================================
// Generate service-worker.js
// ============================================================================
const serviceWorker = `// service-worker.js
// Auto-generated by scripts/generate-pwa-assets.js - DO NOT EDIT MANUALLY
const CACHE_NAME = 'saas-app-v${APP_VERSION}';
const STATIC_ASSETS = [
  '/icon-192.png?v=${APP_VERSION}',
  '/icon-512.png?v=${APP_VERSION}',
  '/logo.svg',
];

// Install event: Cache static assets but DON'T auto-activate
// We wait for user confirmation via SKIP_WAITING message
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS);
    })
  );
  // Don't call skipWaiting() here anymore - wait for user action
});

// Message event: Handle commands from the client
self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') {
    // User clicked "Refresh Now" - activate immediately
    self.skipWaiting();
  }
});

// Activate event: Clean up old caches and notify clients
self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Clean up old caches
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter((name) => name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      );

      // Take control of all pages immediately
      await self.clients.claim();

      // Notify all clients to reload
      const clients = await self.clients.matchAll({ type: 'window' });
      clients.forEach((client) => {
        client.postMessage({ type: 'RELOAD_PAGE' });
      });
    })()
  );
});

// Fetch event: Network-first for navigation, cache-first for static assets
self.addEventListener('fetch', (event) => {
  const { request } = event;

  // Navigation requests (HTML pages): always go to network so middleware
  // redirects work correctly. Fall back to cache only if offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => {
        return caches.match(request);
      })
    );
    return;
  }

  // Static assets: serve from cache, fall back to network
  event.respondWith(
    caches.match(request).then((cached) => {
      return cached || fetch(request);
    })
  );
});

// Push notification event: Display notification from server
self.addEventListener('push', (event) => {
  if (!event.data) return;

  try {
    const payload = event.data.json();
    const options = {
      body: payload.body || '',
      icon: '/icon-192.png?v=${APP_VERSION}',
      badge: '/icon-192.png?v=${APP_VERSION}',
      tag: payload.tag || 'default',
      data: payload.data || {},
      vibrate: [200, 100, 200],
      requireInteraction: false,
    };

    event.waitUntil(
      self.registration.showNotification(
        payload.title || 'Metric Gym Manager',
        options
      )
    );
  } catch (err) {
    console.error('Push event error:', err);
  }
});

// Notification click: Navigate to relevant page
self.addEventListener('notificationclick', (event) => {
  event.notification.close();

  const url = event.notification.data?.url || '/members';

  event.waitUntil(
    self.clients
      .matchAll({ type: 'window', includeUncontrolled: true })
      .then((clientList) => {
        for (const client of clientList) {
          if (client.url.includes(self.location.origin) && 'focus' in client) {
            client.navigate(url);
            return client.focus();
          }
        }
        return self.clients.openWindow(url);
      })
  );
});
`;

const serviceWorkerPath = path.join(__dirname, '../public/service-worker.js');
fs.writeFileSync(serviceWorkerPath, serviceWorker);
console.log('✅ Generated service-worker.js');

// ============================================================================
// Generate version info for layout.tsx to consume
// ============================================================================
const versionInfo = `// Auto-generated by scripts/generate-pwa-assets.js - DO NOT EDIT MANUALLY
export const PWA_VERSION = '${APP_VERSION}';
`;

const versionPath = path.join(__dirname, '../src/lib/pwa-version.ts');
fs.writeFileSync(versionPath, versionInfo);
console.log('✅ Generated src/lib/pwa-version.ts');

console.log(`\n🎉 All PWA assets generated successfully with version ${APP_VERSION}!\n`);
