#!/usr/bin/env node

/**
 * Generates PWA assets (manifest.json, service-worker.js) with automated versioning
 * Version is sourced from package.json to ensure consistency across all PWA files
 */

const fs = require('fs')
const path = require('path')

// Read version from package.json (single source of truth)
const packageJson = require('../package.json')
const APP_VERSION = packageJson.version

console.log(`📦 Generating PWA assets with version ${APP_VERSION}...`)

// ============================================================================
// Generate manifest.json
// ============================================================================
// `background_color` is what the OS paints during the splash, before the app
// has rendered anything, and `theme_color` tints the system chrome around it.
// Both were the pre-dark-flip defaults, so launching the installed app flashed
// a WHITE screen and then painted the near-black workspace over it. The values
// are `surface-base` from `globals.css` — this file sits outside the token
// system (it is a Node script, not a component), so the parity test below
// checks the two agree rather than trusting the comment.
//
// Presentation only: `start_url` and `display` are deliberately unchanged
// (mobile rebuild plan §16, correction C12 — those are product decisions,
// open item o11).
const SURFACE_BASE = '#08080a'

const manifest = {
  name: 'Metric Gym OS',
  short_name: 'Metric Gym OS',
  start_url: '/members',
  display: 'standalone',
  background_color: SURFACE_BASE,
  theme_color: SURFACE_BASE,
  icons: [
    {
      src: `/icon-192.png?v=${APP_VERSION}`,
      sizes: '192x192',
      type: 'image/png',
    },
    {
      src: `/icon-512.png?v=${APP_VERSION}`,
      sizes: '512x512',
      type: 'image/png',
    },
  ],
}

const manifestPath = path.join(__dirname, '../public/manifest.json')
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2))
console.log('✅ Generated manifest.json')

// ============================================================================
// Generate service-worker.js
// ============================================================================
const serviceWorker = `// service-worker.js
// Auto-generated by scripts/generate-pwa-assets.js - DO NOT EDIT MANUALLY
const CACHE_NAME = 'saas-app-v${APP_VERSION}';
const STATIC_ASSETS = [
  '/icon-192.png?v=${APP_VERSION}',
  '/icon-512.png?v=${APP_VERSION}',
  '/logo.svg',
];

// Install event: Cache static assets but DON'T auto-activate
// We wait for user confirmation via SKIP_WAITING message
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS);
    })
  );
  // Don't call skipWaiting() here anymore - wait for user action
});

// Message event: Handle commands from the client
self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') {
    // User clicked "Refresh Now" - activate immediately
    self.skipWaiting();
  }
});

// Activate event: Clean up old caches and take control.
// We deliberately do NOT tell clients to reload here. The client
// (ServiceWorkerRegistration) reloads exactly once in response to the
// \`controllerchange\` event that clients.claim() triggers, and only when the
// user asked for the update — a single, race-free reload path.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Clean up old caches
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter((name) => name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      );

      // Take control of all pages immediately so \`controllerchange\` fires on
      // the client that requested the update.
      await self.clients.claim();
    })()
  );
});

// Fetch event: network-first for navigations; cache-first ONLY for the
// small set of pre-cached static assets. Everything else (JS bundles, CSS,
// API calls, third-party requests) is deliberately NOT intercepted so a
// stale worker can never serve outdated application code ("zombie cache").
self.addEventListener('fetch', (event) => {
  const { request } = event;

  if (request.method !== 'GET') return;

  // Navigation requests (HTML pages): always go to network so middleware
  // redirects work correctly. Fall back to cache only if offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => {
        return caches.match(request);
      })
    );
    return;
  }

  // Only same-origin, explicitly pre-cached assets are served cache-first.
  let isPrecached = false;
  try {
    const url = new URL(request.url);
    isPrecached =
      url.origin === self.location.origin &&
      STATIC_ASSETS.includes(url.pathname + url.search);
  } catch {
    return; // Unparseable URL — let the browser handle it.
  }
  if (!isPrecached) return; // Default browser handling — no interception.

  event.respondWith(
    caches.match(request).then((cached) => {
      return cached || fetch(request);
    })
  );
});
`

const serviceWorkerPath = path.join(__dirname, '../public/service-worker.js')
fs.writeFileSync(serviceWorkerPath, serviceWorker)
console.log('✅ Generated service-worker.js')

// ============================================================================
// Generate version info for layout.tsx to consume
// ============================================================================
const versionInfo = `// Auto-generated by scripts/generate-pwa-assets.js - DO NOT EDIT MANUALLY
export const PWA_VERSION = '${APP_VERSION}';
`

const versionPath = path.join(__dirname, '../src/lib/pwa-version.ts')
fs.writeFileSync(versionPath, versionInfo)
console.log('✅ Generated src/lib/pwa-version.ts')

console.log(
  `\n🎉 All PWA assets generated successfully with version ${APP_VERSION}!\n`
)
